"""Transcribe the gyro on-the-fly reference into GyroOnTheFlyVectors.cs.

The reference is shimmer-web-sdk's tests/fixtures/gyro_on_the_fly_hostcore.json: raw gyro and
shimmer-host-core's calibrated gyro, as IEEE-754 bits, from three of host-core's conformance
traces. host-core is held bit-exact with the Java driver, so matching it is matching Consensys.

ShimmerUnitTests.csproj is the old style and has no way to load a data file, so the vectors are
transcribed into C# rather than read at run time. Regenerate; do not hand-edit:

    python gen_gyro_on_the_fly_vectors.py <path to gyro_on_the_fly_hostcore.json> <source note>
"""

import json
import sys
from pathlib import Path

OUT = Path(__file__).with_name("GyroOnTheFlyVectors.cs")


def doubles(values):
    return ", ".join(repr(float(v)) for v in values)


def main():
    fixture_path = Path(sys.argv[1])
    source_note = sys.argv[2] if len(sys.argv) > 2 else fixture_path.name
    fixture = json.loads(fixture_path.read_text(encoding="utf-8"))

    lines = [
        "// Generated by gen_gyro_on_the_fly_vectors.py. Do not hand-edit; regenerate.",
        f"// Source: {source_note}",
        "namespace ShimmerBluetoothTests",
        "{",
        "    internal static class GyroOnTheFlyVectors",
        "    {",
        "        internal sealed class Case",
        "        {",
        "            public string Name;",
        "            public double SamplingRate;",
        "            public double[] Offset;",
        "            /// <summary>The diagonal of the sensitivity matrix.</summary>",
        "            public double[] Sensitivity;",
        "            /// <summary>The alignment matrix, row-major.</summary>",
        "            public double[] Alignment;",
        "            public int[,] Raw;",
        "            /// <summary>host-core's calibrated gyro, deg/s, as IEEE-754 bits.</summary>",
        "            public ulong[,] ExpectedCalBits;",
        "        }",
        "",
        "        internal static readonly Case[] Cases =",
        "        {",
    ]
    for case in fixture["cases"]:
        cal = case["calibration"]
        assert len(case["raw"]) == len(case["expectedCalBits"])
        lines += [
            "            new Case",
            "            {",
            f"                Name = \"{case['name']}\",",
            f"                SamplingRate = {float(case['samplingRateHz'])!r},",
            f"                Offset = new double[] {{ {doubles(cal['offset'])} }},",
            f"                Sensitivity = new double[] {{ {doubles(cal['sensitivity'])} }},",
            f"                Alignment = new double[] {{ {doubles(cal['alignment'])} }},",
            "                Raw = new int[,]",
            "                {",
        ]
        lines += [f"                    {{ {r[0]}, {r[1]}, {r[2]} }}," for r in case["raw"]]
        lines += [
            "                },",
            "                ExpectedCalBits = new ulong[,]",
            "                {",
        ]
        lines += [
            "                    { " + ", ".join(f"0x{b}UL" for b in bits) + " },"
            for bits in case["expectedCalBits"]
        ]
        lines += [
            "                },",
            "            },",
        ]
    lines += [
        "        };",
        "    }",
        "}",
        "",
    ]
    OUT.write_bytes("\r\n".join(lines).encode("utf-8"))
    print(f"wrote {OUT} ({len(fixture['cases'])} cases)")


if __name__ == "__main__":
    main()
